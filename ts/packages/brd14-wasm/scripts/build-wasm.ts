// build-wasm.ts — builds the brd14-wasm crate for wasm32-unknown-unknown and embeds
// the module into src/wasm-bytes.ts (generated, gitignored) as base64.
//
//   node ts/packages/brd14-wasm/scripts/build-wasm.ts [--core speed|memory]
//   bun  ts/packages/brd14-wasm/scripts/build-wasm.ts
//
// It runs `cargo build -p brd14-wasm --target wasm32-unknown-unknown --release` with
// native/rust as the working directory, so rust-toolchain.toml pins the compiler and
// the crate's build.rs applies the fixed-memory link arguments. The speed core is the
// default; `--core memory` (or BRD14_WASM_CORE=memory) selects the table-free core.
// `cargo` is taken from $CARGO, then PATH, then ~/.cargo/bin.
//
// The generated file exports the module as one base64 string plus its byte length,
// SHA-256 and core, so the loader (src/module.ts) can decode and instantiate it
// synchronously at import with no file or network access.

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const PKG = fileURLToPath(new URL("../", import.meta.url));
const RUST = resolve(PKG, "../../../native/rust");
const WASM = resolve(RUST, "target/wasm32-unknown-unknown/release/brd14_wasm.wasm");
const OUT = resolve(PKG, "src/wasm-bytes.ts");

const argv = process.argv.slice(2);
const coreArg = argv.indexOf("--core");
const core = coreArg >= 0 ? argv[coreArg + 1] : process.env["BRD14_WASM_CORE"] ?? "speed";
if (core !== "speed" && core !== "memory") {
  console.error(`build-wasm: unknown core ${JSON.stringify(core)} (speed | memory)`);
  process.exit(2);
}

function cargoCandidates(): string[] {
  const out: string[] = [];
  if (process.env["CARGO"]) out.push(process.env["CARGO"]);
  out.push("cargo", resolve(homedir(), ".cargo/bin/cargo"));
  return out;
}

function build(): void {
  const args = ["build", "-p", "brd14-wasm", "--target", "wasm32-unknown-unknown", "--release"];
  if (core === "memory") args.push("--features", "memory");
  let lastError = "";
  for (const cargo of cargoCandidates()) {
    const r = spawnSync(cargo, args, { cwd: RUST, stdio: ["ignore", "inherit", "inherit"] });
    if (r.error !== undefined) {
      lastError = `${cargo}: ${r.error.message}`;
      continue; // not found here; try the next candidate
    }
    if (r.status !== 0) {
      console.error(`build-wasm: ${cargo} ${args.join(" ")} failed with status ${r.status}`);
      process.exit(1);
    }
    return;
  }
  console.error(`build-wasm: cargo not found (${lastError}); install Rust with the wasm32-unknown-unknown target (native/rust/rust-toolchain.toml)`);
  process.exit(1);
}

build();
if (!existsSync(WASM)) {
  console.error(`build-wasm: cargo succeeded but ${WASM} is missing`);
  process.exit(1);
}

const bytes = readFileSync(WASM);
const sha256 = createHash("sha256").update(bytes).digest("hex");
const base64 = bytes.toString("base64");

const source = `// wasm-bytes.ts — GENERATED by scripts/build-wasm.ts; do not edit (gitignored).
// Source: native/rust/target/wasm32-unknown-unknown/release/brd14_wasm.wasm (${core} core).
// The module is decoded with atob and instantiated synchronously by ./module.ts.

/** The brd14 WebAssembly module, base64. */
export const WASM_BASE64 = "${base64}";

/** Byte length of the decoded module. */
export const WASM_BYTE_LENGTH = ${bytes.length};

/** SHA-256 of the module bytes, lowercase hex. */
export const WASM_SHA256 = "${sha256}";

/** The core the module was built with. */
export const WASM_CORE: "speed" | "memory" = "${core}";
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, source);
console.log(`build-wasm: ${core} core, ${bytes.length} bytes, sha256 ${sha256.slice(0, 16)}… → ${OUT}`);
