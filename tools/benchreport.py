"""benchreport.py — render bench/results/*.json into docs/benchmarks.md.

    python3 tools/benchreport.py [--results bench/results] [--out docs/benchmarks.md]

The page is generated; edit the prose here, not in the output. Numbers are only
ever copied from the JSON files, which carry the machine and toolchain they
were measured on (schema: bench/README.md).
"""

from __future__ import annotations

import argparse
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADLINE_OPS = ["encode", "decode", "hash32", "mint"]
IMPL_ORDER = ["c", "rust", "go", "ts-wasm", "ts", "python"]
VARIANT_ORDER = ["speed", "memory", "reference", "wasm", "pure"]

# KAN document identity of the generated page: minted once (scripts/mint.sh KAN), never
# regenerated; tools/doclint.py checks the page like every other.
FRONTMATTER = """\
---
id: "KAN0R9YJSyiaeW"
slug: "DOCS-BENCHMARKS"
type: "guide"
version: "1.3"
path: "docs/benchmarks.md"
title: "Benchmarks"
summary: "Measured codec costs per implementation and runtime, generated from bench/results by tools/benchreport.py, with the protocol and how to reproduce."
tags: ["benchmarks", "measurement"]
group: "measurement"
language: "en"
audience: ["developer", "agent"]
---

"""

# The status paragraph of the committed results (it used to be passed with --note).
STATUS = (
    "These are the **W2 baseline**: one run per tree, each measured by the agent that built it, in different windows, on a shared 4-vCPU Xeon (@ 2.10 GHz per lscpu at run time) while other agents were compiling. CV was 7–17% on several runs, above the protocol's 5% threshold. Read the **ratios** (speed vs memory, wasm vs pure, 3.14 vs 3.14t), not the absolute values. Bun ran with the container's default `BUN_OPTIONS=--smol`. The consolidated same-session run is planned in [roadmap.md](roadmap.md)."
)

NAV = ("[Index](index.md#toc) · [Protocol](../bench/README.md#toc) · [Runtimes](runtimes.md#toc) · "
       "[Hardening](hardening.md#toc) · [Structures](structures/README.md#toc)\n")

TOC = """\
<a id="toc"></a>

## In this document

- [Headline: ns/op (× C speed)](#headline)
- [Every operation, with allocation](#operations)
- [Reproduce](#reproduce)
"""

INTRO = """\
# Benchmarks

> Generated by [`tools/benchreport.py`](../tools/benchreport.py) from
> [`bench/results/`](../bench/results/). The protocol is in [`bench/README.md`](../bench/README.md).

**What these numbers are.** Each figure is the median time per operation, in nanoseconds, over at
least 10 samples. Every implementation runs over the same corpus: the first 4096 rows of
`vectors/valid.tsv`. Runs are pinned to one core where possible. The *× C* columns divide by the
C `speed` core measured in the same session, so the ratios stay comparable when the absolute
numbers drift between machines.

**What they are not.** They are microbenchmarks of the codec, not of a service. A 10 ns encode and
a 40 ns encode are the same thing next to one network round trip. The numbers matter for two
things: bulk paths (ETL, log replay, index rebuilds, batch APIs) and the allocation story, since an
allocation is paid again in GC pressure.
"""


def load(results_dir: pathlib.Path) -> list[dict]:
    runs = []
    for p in sorted(results_dir.glob("*.json")):
        try:
            d = json.loads(p.read_text())
        except json.JSONDecodeError:
            continue
        if isinstance(d, dict) and "results" in d and "impl" in d:
            d["_file"] = p.name
            runs.append(d)
    return runs


def order_key(r: dict) -> tuple:
    impl = r["impl"]
    v = r.get("variant", "")
    return (IMPL_ORDER.index(impl) if impl in IMPL_ORDER else 99,
            VARIANT_ORDER.index(v) if v in VARIANT_ORDER else 99, r.get("runtime", ""))


def ops_of(r: dict) -> dict[str, dict]:
    return {x["op"]: x for x in r["results"]}


def fmt_ns(x: float | None) -> str:
    if x is None:
        return "—"
    if x >= 1000:
        return f"{x / 1000:.2f} µs"
    if x >= 100:
        return f"{x:.0f}"
    return f"{x:.1f}"


def render(runs: list[dict], note: str = "") -> str:
    runs = sorted(runs, key=order_key)
    base = next((ops_of(r) for r in runs if r["impl"] == "c" and r.get("variant") == "speed"), {})
    machines = sorted({r.get("machine", "?") for r in runs})
    out = [FRONTMATTER + INTRO]
    if note:
        out.append(f"> **Status.** {note}\n")
    out.append(f"**Machine:** {', '.join(machines)}. **Runs:** {len(runs)} result files.\n")
    out.append(NAV)
    out.append(TOC)

    out.append('<a id="headline"></a>\n')
    out.append("## Headline: ns/op (× C speed)\n")
    out.append("| Implementation | Variant | Runtime | " + " | ".join(HEADLINE_OPS) + " |")
    out.append("|---|---|---|" + "---:|" * len(HEADLINE_OPS))
    for r in runs:
        ops = ops_of(r)
        cells = []
        for op in HEADLINE_OPS:
            x = ops.get(op, {}).get("ns_per_op")
            b = base.get(op, {}).get("ns_per_op")
            ratio = f" ({x / b:.1f}×)" if x is not None and b else ""
            cells.append(fmt_ns(x) + ratio)
        out.append(f"| {r['impl']} | {r.get('variant', '')} | {r.get('runtime', '')} | " + " | ".join(cells) + " |")
    out.append("")

    out.append('<a id="operations"></a>\n')
    out.append("## Every operation, with allocation where the runtime reports it\n")
    for r in runs:
        out.append(f"### {r['impl']} · {r.get('variant', '')} · {r.get('runtime', '')}\n")
        pinned = "pinned" if r.get("pinned") else "not pinned"
        out.append(f"`{r['_file']}` — {pinned}, corpus: {r.get('corpus', '?')}\n")
        out.append("| op | ns/op | MAD | samples | allocs/op | bytes/op |")
        out.append("|---|---:|---:|---:|---:|---:|")
        for x in r["results"]:
            mad = x.get("mad_ns")
            out.append(f"| {x['op']} | {fmt_ns(x.get('ns_per_op'))} | "
                       f"{'—' if mad is None else f'{mad:.2f}'} | {x.get('samples', '—')} | "
                       f"{x.get('allocs_per_op', '—')} | {x.get('bytes_per_op', '—')} |")
        out.append("")

    out.append('<a id="reproduce"></a>\n')
    out.append("## Reproduce\n")
    out.append("```bash\n. scripts/env.sh\nmake bench                    # every tree writes bench/results/*.json\n"
               "python3 tools/benchreport.py  # renders this page\n```\n")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=str(ROOT / "bench" / "results"))
    ap.add_argument("--out", default=str(ROOT / "docs" / "benchmarks.md"))
    ap.add_argument("--note", default=STATUS, help="the status paragraph rendered under the intro")
    a = ap.parse_args()
    runs = load(pathlib.Path(a.results))
    pathlib.Path(a.out).write_text(render(runs, a.note), encoding="utf-8")
    print(f"{a.out}: {len(runs)} result files")


if __name__ == "__main__":
    main()
